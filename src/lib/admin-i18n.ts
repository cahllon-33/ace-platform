export type AdminMessageKey = keyof typeof ADMIN_EN;

export function isAdminHebrew(localeId: string) {
  return localeId === "he";
}

export function adminLocaleId(localeId: string): "he" | "en" {
  return isAdminHebrew(localeId) ? "he" : "en";
}

export function adminDir(localeId: string): "rtl" | "ltr" {
  return isAdminHebrew(localeId) ? "rtl" : "ltr";
}

export function adminLang(localeId: string) {
  return isAdminHebrew(localeId) ? "he" : "en";
}

export function translateAdmin(
  localeId: string,
  key: AdminMessageKey,
  values?: Record<string, string | number>,
) {
  const bag = adminLocaleId(localeId) === "he" ? ADMIN_HE : ADMIN_EN;
  return interpolate(bag[key] ?? ADMIN_EN[key], values);
}
